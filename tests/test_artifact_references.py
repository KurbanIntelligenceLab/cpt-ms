"""An artifact that names another artifact must name one that exists.

The manuscript's promise is that a reader can trace any number to a record and any
record to code. Seven artifacts quietly broke that: an earlier rename stripped the
WS/CPR workstream prefixes from result filenames but never touched the filenames
recorded *inside* other artifacts, so their provenance pointed at
`results/WS3_crystal_A1_seed0.json` and similar files that no longer existed.
Nothing failed, because nothing checked.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"

REF = re.compile(r"results/[A-Za-z0-9_.*{}-]+\.json")

# smc_tuned.json is regenerated by scripts/crystal/smc_tune.py, which samples from a
# trained checkpoint. Checkpoints are build products and are not distributed, so this
# one cannot be refreshed on a clean tree. Listed here rather than skipped silently:
# it is a known stale reference, and it should be regenerated on the next run that has
# the checkpoint to hand.
KNOWN_STALE = {"smc_tuned.json", "smc_tuned_smoke.json"}


def _artifacts() -> list[Path]:
    return sorted(p for p in RESULTS.glob("*.json") if p.name != "run_ledger.jsonl")


@pytest.mark.parametrize("artifact", _artifacts(), ids=lambda p: p.name)
def test_referenced_artifacts_exist(artifact: Path) -> None:
    if artifact.name in KNOWN_STALE:
        pytest.skip(f"{artifact.name} needs a checkpoint to regenerate; see KNOWN_STALE")
    dangling = sorted(
        ref for ref in set(REF.findall(artifact.read_text()))
        if "*" not in ref and "{" not in ref and not (ROOT / ref).exists()
    )
    assert not dangling, (
        f"{artifact.name} names artifacts that do not exist: {dangling}. "
        f"Regenerate it by rerunning the script in its 'script' field.")
